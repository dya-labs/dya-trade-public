import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import type { ReactNode } from "react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { WalletDashboard } from "../../id/components/wallet-dashboard";
import { getAllBalances } from "@dya/wallet-ui/lib/near/http/account-client";
import { prepareConfidentialAccess, unlockConfidentialAccessWithBalances } from "@dya/wallet-ui/lib/near/http/confidential-client";
import { startAuthentication } from "@simplewebauthn/browser";
import { ConfidentialAccessRequired } from "@dya/wallet-ui/lib/near/domain/confidential-access-error";
import { toast } from "@dya/ui/lib/toast";
vi.mock("@dya/ui/lib/toast", () => ({ toast: vi.fn() }));
const state = vi.hoisted(() => ({ client: null as QueryClient | null }));
vi.mock("next/link", () => ({ default: ({ href, children }: { href: string; children: ReactNode }) => <a href={href}>{children}</a> }));
vi.mock("next/image", () => ({ default: ({ src, alt }: { src: string; alt: string }) => <img src={src} alt={alt} /> }));
vi.mock("@dya/wallet-ui/components/wallet-query-provider", () => ({ WalletQueryProvider: ({ children }: { children: ReactNode }) => <QueryClientProvider client={state.client!}>{children}</QueryClientProvider> }));
vi.mock("@dya/wallet-ui/lib/near/http/account-client", () => ({ getSession: vi.fn(), getAllBalances: vi.fn(), logout: vi.fn() }));
vi.mock("@dya/wallet-ui/lib/near/http/catalog-client", () => ({ getCatalog: vi.fn() }));
vi.mock("@dya/wallet-ui/lib/near/http/confidential-client", () => ({ prepareConfidentialAccess: vi.fn(), unlockConfidentialAccessWithBalances: vi.fn() }));
vi.mock("@simplewebauthn/browser", () => ({ startAuthentication: vi.fn(), startRegistration: vi.fn() }));
vi.mock("@dya/wallet-ui/components/wallet-assets", () => ({ WalletAssets: () => <p>Private asset rows</p> }));
vi.mock("../../id/components/wallet-activity", () => ({ WalletActivity: () => null }));
vi.mock("../../id/components/wallet-recovery", () => ({ WalletRecovery: () => null }));
vi.mock("../../id/components/wallet-transfer", () => ({ WalletTransfer: () => null }));
vi.mock("../../id/components/wallet-page-header", () => ({ WalletPageHeader: ({ disabled }: { disabled: boolean }) => <button disabled={disabled}>Account menu</button> }));
const key = ["near", "account", "balance-access-account", "balances", "confidential", "all"];
const balances = { accountId: "balance-access-account", blockHeight: 1, checkedAt: 1, assets: [{ assetId: "synthetic-usdc", symbol: "USDC", decimals: 6, raw: "2500000", amount: "2.5" }] };
function mount() {
  state.client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  state.client.setQueryData(["near", "session"], { account: { id: "balance-access-account", kind: "passkey" } });
  state.client.setQueryData(["near", "catalog"], { assets: [{ assetId: "synthetic-usdc", symbol: "USDC", price: "1" }] });
  state.client.setQueryData(key, balances);
  render(<WalletDashboard />);
}
async function refresh() { await act(async () => { await state.client!.invalidateQueries({ queryKey: key }); }); }
beforeEach(() => {
  vi.resetAllMocks();
  vi.mocked(getAllBalances).mockResolvedValue(balances);
  vi.mocked(prepareConfidentialAccess).mockResolvedValue({ options: { challenge: "synthetic-access" } } as Awaited<ReturnType<typeof prepareConfidentialAccess>>);
  vi.mocked(startAuthentication).mockResolvedValue({ id: "synthetic-assertion" } as Awaited<ReturnType<typeof startAuthentication>>);
  vi.mocked(unlockConfidentialAccessWithBalances).mockResolvedValue({ unlocked: true });
});
afterEach(() => { cleanup(); state.client?.clear(); state.client = null; });
it("hides cached amounts, asset rows and spending controls after confidential access expires", async () => {
  mount();
  expect(screen.getByLabelText("Estimated portfolio value")).toHaveTextContent("$2.50");
  expect(screen.getByText("Private asset rows")).toBeVisible();
  vi.mocked(getAllBalances).mockRejectedValue(new ConfidentialAccessRequired());
  await refresh();
  expect(await screen.findByRole("button", { name: "Unlock balances" })).toBeEnabled();
  expect(screen.queryByLabelText("Estimated portfolio value")).toBeNull();
  expect(screen.queryByText("Private asset rows")).toBeNull();
  expect(screen.queryByRole("button", { name: "Send" })).toBeNull();
  expect(screen.queryByRole("button", { name: "Receive" })).toBeNull();
  expect(state.client!.getQueryData(key)).toEqual(balances);
  expect(screen.queryByText(/showing last known balances/)).toBeNull();
});
it("keeps cached amounts visible during a transient refresh failure while blocking Send", async () => {
  mount();
  vi.mocked(getAllBalances).mockRejectedValueOnce(new Error("Synthetic outage"));
  await refresh();
  expect(await screen.findByText("Updates delayed · showing last known balances.")).toBeVisible();
  expect(screen.getByLabelText("Estimated portfolio value")).toHaveTextContent("$2.50");
  expect(screen.getByRole("button", { name: "Send" })).toBeDisabled();
  fireEvent.click(screen.getByRole("button", { name: "Retry" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Send" })).toBeEnabled());
  expect(screen.queryByText(/Updates delayed/)).toBeNull();
});
it("locks duplicate unlock actions until device approval finishes then refreshes private balances", async () => {
  mount();
  vi.mocked(getAllBalances).mockRejectedValueOnce(new ConfidentialAccessRequired());
  await refresh();
  let approve!: (value: Awaited<ReturnType<typeof startAuthentication>>) => void;
  vi.mocked(startAuthentication).mockImplementationOnce(() => new Promise(resolve => { approve = resolve; }));
  fireEvent.click(await screen.findByRole("button", { name: "Unlock balances" }));
  expect(await screen.findByRole("button", { name: "Confirming…" })).toBeDisabled();
  expect(screen.getByRole("button", { name: "Account menu" })).toBeDisabled();
  expect(unlockConfidentialAccessWithBalances).not.toHaveBeenCalled();
  await act(async () => approve({ id: "synthetic-approved" } as Awaited<ReturnType<typeof startAuthentication>>));
  await waitFor(() => expect(screen.getByRole("button", { name: "Send" })).toBeEnabled());
  expect(prepareConfidentialAccess).toHaveBeenCalledOnce();
  expect(startAuthentication).toHaveBeenCalledWith({ optionsJSON: { challenge: "synthetic-access" } });
  expect(unlockConfidentialAccessWithBalances).toHaveBeenCalledWith({ id: "synthetic-approved" });
  expect(getAllBalances).toHaveBeenCalledTimes(2);
  expect(screen.getByLabelText("Estimated portfolio value")).toHaveTextContent("$2.50");
});
it("keeps expired balances hidden after cancelled device confirmation and permits unlock retry", async () => {
  mount();
  vi.mocked(getAllBalances).mockRejectedValueOnce(new ConfidentialAccessRequired());
  await refresh();
  vi.mocked(startAuthentication).mockRejectedValueOnce(new DOMException("Opaque browser diagnostic", "NotAllowedError"));
  fireEvent.click(await screen.findByRole("button", { name: "Unlock balances" }));
  await waitFor(() => expect(toast).toHaveBeenCalledWith("Confirmation cancelled"));
  expect(screen.getByRole("button", { name: "Unlock balances" })).toBeEnabled();
  expect(screen.queryByLabelText("Estimated portfolio value")).toBeNull();
  expect(screen.queryByText("Opaque browser diagnostic")).toBeNull();
  expect(unlockConfidentialAccessWithBalances).not.toHaveBeenCalled();
  fireEvent.click(await screen.findByRole("button", { name: "Unlock balances" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Send" })).toBeEnabled());
  expect(unlockConfidentialAccessWithBalances).toHaveBeenCalledOnce();
  expect(toast).toHaveBeenCalledOnce();
});
