import { withTokenPolicy } from "./fixtures/token-policy";
import { approvedTestNetworks } from "./fixtures/network-policy";
import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { expect, it, vi } from "vitest";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { DialogDrawer, DialogDrawerContent } from "@dya/ui/components/dialog-drawer";
import { LegacyDepositForm } from "@/components/near/transfers";
import { DEFAULT_PAIR } from "@/lib/near/domain/catalog";
vi.mock("@dya/wallet-ui/components/near/network-mark", () => ({ NetworkMark: () => <span /> }));
vi.mock("@dya/wallet-ui/components/near/asset-mark", () => ({ AssetMark: () => <span /> }));
vi.mock("@/components/near/use-activity", () => ({ useTransfers: () => ({ data: { deposits: [], withdrawals: [] } }) }));
vi.mock("@dya/wallet-ui/components/near/use-deposit-status", () => ({ useDepositStatus: () => ({ data: null }) }));
vi.mock("@dya/wallet-ui/lib/near/http/catalog-client", () => ({ getCatalog: async () => (withTokenPolicy({ networks: approvedTestNetworks, assets: [{ ...DEFAULT_PAIR.quote, coingeckoId: "usd-coin" }, { ...DEFAULT_PAIR.quote, assetId: "base-usdc", blockchain: "base", coingeckoId: "usd-coin" }] })) }));
it("starts with USDC and no network, requiring selection before creating instructions", async () => {
  render(<QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}><DialogDrawer open><DialogDrawerContent><LegacyDepositForm accountId="test" /></DialogDrawerContent></DialogDrawer></QueryClientProvider>);
  vi.stubGlobal("PointerEvent", MouseEvent);
  fireEvent.click(screen.getByRole("checkbox"));
  fireEvent.click(screen.getByRole("button", { name: "Continue" }));
  await waitFor(() => expect(screen.getByRole("button", { name: "Deposit token" }).hasAttribute("disabled")).toBe(false));
  expect(screen.getByRole("button", { name: "Deposit token" }).textContent).toContain("USDC");
  expect(screen.getByRole("button", { name: "Deposit network" }).textContent).toContain("Select network");
  expect(screen.getByRole("button", { name: "Create deposit address" }).hasAttribute("disabled")).toBe(true);
  expect(screen.queryByRole("tab", { name: "Withdraw" })).toBeNull();
  expect(screen.queryByRole("textbox", { name: /Amount/ })).toBeNull();
  expect(screen.queryByRole("textbox", { name: /Refund address/ })).toBeNull();
  expect(screen.getByRole("heading", { name: "Deposit" })).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Deposit token" }));
  expect(screen.getByRole("heading", { name: "Select token" })).toBeTruthy();
  expect(screen.queryByRole("heading", { name: "Deposit" })).toBeNull();
  fireEvent.change(screen.getByRole("textbox", { name: "Search tokens" }), { target: { value: "missing" } });
  expect(screen.getByText("No tokens found.")).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Back to deposit" }));
  expect(screen.getByRole("button", { name: "Deposit token" }).textContent).toContain("USDC");
  fireEvent.click(screen.getByRole("button", { name: "Deposit network" }));
  expect(screen.getByRole("textbox", { name: "Search networks" })).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Base" }));
  expect(screen.getByRole("button", { name: "Deposit network" }).textContent).toContain("Base");
  expect(screen.getByRole("button", { name: "Create deposit address" }).hasAttribute("disabled")).toBe(false);
});
