import { readFile, writeFile } from 'node:fs/promises';

// Refresh the checked-in icons only from the verified identity mapping.
const source = await readFile(new URL('../../wallet-contracts/src/market-data/coinmarketcap.ts', import.meta.url), 'utf8');
const mapping = source.match(/export const coinMarketCapIdentities[^=]*= (\{[\s\S]*?\n\});/)[1];
const identities = JSON.parse(mapping);
const images = {};
for (const id of [...new Set(Object.values(identities))].sort((a, b) => a - b)) {
  const response = await fetch(`https://s2.coinmarketcap.com/static/img/coins/64x64/${id}.png`, { signal: AbortSignal.timeout(15000), redirect: 'error' });
  if (!response.ok) throw new Error(`Icon ${id}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (!bytes.subarray(0, 8).equals(Buffer.from('89504e470d0a1a0a', 'hex')) || bytes.length > 100000) throw new Error(`Invalid PNG ${id}`);
  images[id] = `data:image/png;base64,${bytes.toString('base64')}`;
}
const output = `// Generated by scripts/update-token-icons.mjs. One image per verified token.\nconst identities: Record<string, number> = ${JSON.stringify(identities, null, 2)};\nconst images: Record<number, string> = ${JSON.stringify(images, null, 2)};\nexport function bundledTokenIcon(identity: string) { return images[identities[identity]]; }\n`;
await writeFile(new URL('../src/lib/bundled-token-icons.ts', import.meta.url), output);
console.log(`Bundled ${Object.keys(images).length} icons (${Buffer.byteLength(output)} bytes).`);
