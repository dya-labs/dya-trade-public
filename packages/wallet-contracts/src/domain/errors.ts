export type StaticErrorCode = {
  [C in ErrorCode]: Parameters<(typeof errorMessages)[C]> extends [] ? C : never
}[ErrorCode];

export class AppError<C extends ErrorCode = ErrorCode> extends Error {
  constructor(readonly code: C, ...args: Parameters<(typeof errorMessages)[C]>) {
    super(Reflect.apply(errorMessages[code], undefined, args));
    this.name = "AppError";
  }
}

